// --- re-run safety ---------------------------------------------------------

func TestExistingSecretsArePreserved(t *testing.T) {
	/*
	 * The single most destructive thing a re-run could do. Regenerating secrets
	 * against a live deployment breaks it quietly: the database password stops
	 * matching the volume that already exists, every session is invalidated, and
	 * a changed ENCRYPTION_KEY makes every stored two-factor secret
	 * undecryptable — with no way back.
	 */
	original := RenderEnv(testPlan(), testSecrets())
	recovered := ExistingSecrets(original)
	if recovered == nil {
		t.Fatal("secrets written by this installer must be readable back")
	}
	want := testSecrets()
	if recovered.PostgresPassword != want.PostgresPassword ||
		recovered.JWTAccessSecret != want.JWTAccessSecret ||
		recovered.EncryptionKey != want.EncryptionKey ||
		recovered.JWTRefreshSecret != want.JWTRefreshSecret {
		t.Error("recovered secrets do not match what was written")
	}
}

func TestExistingSecretsRejectsAnIncompleteFile(t *testing.T) {
	// A file with no signing keys was never a working installation; treating it
	// as one would deploy a stack that cannot boot.
	if got := ExistingSecrets("POSTGRES_PASSWORD=abc\n"); got != nil {
		t.Error("a file missing the JWT secrets must not be treated as usable")
	}
	if got := ExistingSecrets(""); got != nil {
		t.Error("an empty file must not be treated as usable")
	}
}

