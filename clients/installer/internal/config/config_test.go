// --- .env rendering --------------------------------------------------------

func TestEnvSetsEverythingComposeRequires(t *testing.T) {
	/*
	 * docker-compose.yml fails fast on a missing required value via `${VAR:?}`.
	 * Missing one here means the stack refuses to start with a Compose error
	 * rather than an installer error — much harder for an operator to act on.
	 */
	env := RenderEnv(testPlan(), testSecrets())
	values := ParseEnv(env)
	for _, required := range []string{
		"POSTGRES_PASSWORD", "ADMIN_PASSWORD",
		"JWT_ACCESS_SECRET", "JWT_REFRESH_SECRET", "ENCRYPTION_KEY",
	} {
		if values[required] == "" {
			t.Errorf("%s is required by Compose but was not written", required)
		}
	}
}

func TestEnvDoesNotSetDatabaseURL(t *testing.T) {
	// Compose DERIVES DATABASE_URL from POSTGRES_*. Writing our own would
	// override the derivation and drift the moment the user changes a password.
	values := ParseEnv(RenderEnv(testPlan(), testSecrets()))
	if _, present := values["DATABASE_URL"]; present {
		t.Error("DATABASE_URL must be left to Compose to derive")
	}
}

func TestEnvPersistsComposeProfiles(t *testing.T) {
	/*
	 * Docker does not remember `--profile`. Without COMPOSE_PROFILES in .env, a
	 * later plain `docker compose up -d` in this directory STOPS the torrent
	 * engine and every companion — which looks like the application broke.
	 */
	p := testPlan()
	p.Companions.Prowlarr = true
	p.Finalize()
	values := ParseEnv(RenderEnv(p, testSecrets()))
	got := values["COMPOSE_PROFILES"]
	if !strings.Contains(got, "qbittorrent") || !strings.Contains(got, "prowlarr") {
		t.Errorf("COMPOSE_PROFILES = %q, want the selected profiles", got)
	}
}

func TestEnvLeavesSSRFAloneWithBundledProwlarr(t *testing.T) {
	/*
	 * The Compose file already defaults SSRF_ALLOW_HOSTS to `prowlarr`. Writing
	 * our own copy would freeze today's default and silently diverge if the
	 * platform widened it — and the failure is invisible: auto-downloads fail
	 * with a blocked-address error while every container looks healthy.
	 */
	p := testPlan()
	p.Companions.Prowlarr = true
	p.Finalize()
	env := RenderEnv(p, testSecrets())
	if _, present := ParseEnv(env)["SSRF_ALLOW_HOSTS"]; present {
		t.Error("with bundled Prowlarr the installer must not set SSRF_ALLOW_HOSTS")
	}
	// But it must explain why, or the next operator "fixes" the omission.
	if !strings.Contains(env, "SSRF_ALLOW_HOSTS is intentionally not set") {
		t.Error("the omission should be explained in the file")
	}
}

