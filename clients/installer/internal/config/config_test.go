// --- state carried across runs ---------------------------------------------

func TestInstalledAtSurvivesAReRun(t *testing.T) {
	/*
	 * It is written from time.Now() every run, so without carrying it forward
	 * the first re-run destroys the record of when the installation actually
	 * happened — the one fact nothing else can reconstruct.
	 */
	p := testPlan()
	original := StateFrom(p, []string{EnvFileName})
	original.InstalledAt = time.Date(2020, 5, 6, 7, 8, 9, 0, time.UTC)

	rerun := StateFrom(p, []string{EnvFileName})
	rerun.CarryForward(original)

	if !rerun.InstalledAt.Equal(original.InstalledAt) {
		t.Errorf("installedAt = %v, want the original %v", rerun.InstalledAt, original.InstalledAt)
	}
}

func TestUnchangedStateRendersIdentically(t *testing.T) {
	// So the writer's ordinary "unchanged" path applies and a no-op re-run
	// leaves no backup behind.
	p := testPlan()
	original := StateFrom(p, []string{EnvFileName})
	rerun := StateFrom(p, []string{EnvFileName})
	rerun.UpdatedAt = rerun.UpdatedAt.Add(time.Hour) // a later run
	rerun.CarryForward(original)

	var a, b strings.Builder
	if err := WriteState(&a, original); err != nil {
		t.Fatal(err)
	}
	if err := WriteState(&b, rerun); err != nil {
		t.Fatal(err)
	}
	if a.String() != b.String() {
		t.Errorf("an unchanged deployment should render identical state:\n%s\n--- vs ---\n%s", a.String(), b.String())
	}
}

func TestChangedTopologyMovesUpdatedAt(t *testing.T) {
	p := testPlan()
	original := StateFrom(p, []string{EnvFileName})

	changed := testPlan()
	changed.Companions.FlareSolverr = true
	changed.Companions.Prowlarr = true
	changed.Finalize()

	rerun := StateFrom(changed, []string{EnvFileName})
	rerun.UpdatedAt = rerun.UpdatedAt.Add(time.Hour)
	rerun.CarryForward(original)

	if rerun.SameShape(original) {
		t.Fatal("adding a companion is a change of shape")
	}
	if rerun.UpdatedAt.Equal(original.UpdatedAt) {
		t.Error("a real change must move updatedAt")
	}
	if !rerun.InstalledAt.Equal(original.InstalledAt) {
		t.Error("a real change must still preserve installedAt")
	}
}

func TestSameShapeSeesEveryTopologyField(t *testing.T) {
	/*
	 * Guards the comparison itself. It is written over zeroed copies rather than
	 * field by field so that a field added later is covered automatically — this
	 * test fails if someone replaces it with an explicit list and forgets one,
	 * because the failure mode is invisible: a real change reporting "unchanged".
	 */
	base := StateFrom(testPlan(), []string{EnvFileName})
	mutations := map[string]func(*State){
		"TorrentEngine":    func(s *State) { s.TorrentEngine = "rtorrent" },
		"Profiles":         func(s *State) { s.Profiles = append(s.Profiles, "prowlarr") },
		"Ports":            func(s *State) { s.Ports["frontend"] = 9999 },
		"StorageMode":      func(s *State) { s.StorageMode = "bind" },
		"MediaRoot":        func(s *State) { s.MediaRoot = "/srv/other" },
		"Prowlarr":         func(s *State) { s.Prowlarr = !s.Prowlarr },
		"FlareSolverr":     func(s *State) { s.FlareSolverr = !s.FlareSolverr },
		"BundledProxy":     func(s *State) { s.BundledProxy = !s.BundledProxy },
		"IntakeConfigured": func(s *State) { s.IntakeConfigured = !s.IntakeConfigured },
		"InstallDirectory": func(s *State) { s.InstallDirectory = "/opt/elsewhere" },
		"GeneratedFiles":   func(s *State) { s.GeneratedFiles = nil },
	}
	for name, mutate := range mutations {
		modified := *base
		modified.Ports = map[string]int{}
		for k, v := range base.Ports {
			modified.Ports[k] = v
		}
		modified.Profiles = append([]string(nil), base.Profiles...)
		modified.GeneratedFiles = append([]string(nil), base.GeneratedFiles...)
		mutate(&modified)

		if modified.SameShape(base) {
			t.Errorf("a change to %s was not seen as a change of shape", name)
		}
	}
}

func TestRemoveBacksUpBeforeDeleting(t *testing.T) {
	// A plan that stops needing an override must not leave the old one behind —
	// Compose would keep merging settings the operator has removed.
	dir := t.TempDir()
	w := &Writer{Dir: dir}
	f := File{Name: OverrideFileName, Mode: ModePublic, Content: "services: {}\n"}
	if _, err := w.Write(f); err != nil {
		t.Fatal(err)
	}
	actions, err := w.Remove(OverrideFileName)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, OverrideFileName)); !os.IsNotExist(err) {
		t.Error("the stale override should have been removed")
	}
	var backed bool
	for _, a := range actions {
		if a.Kind == "backup" {
			content, err := os.ReadFile(a.Path)
			if err != nil {
				t.Fatal(err)
			}
			if string(content) != f.Content {
				t.Errorf("backup holds %q", content)
			}
			backed = true
		}
	}
	if !backed {
		t.Error("removing a file must back it up first")
	}
}

func TestRemovingWhatIsNotThereIsNotAnError(t *testing.T) {
	w := &Writer{Dir: t.TempDir()}
	actions, err := w.Remove(OverrideFileName)
	if err != nil {
		t.Fatal(err)
	}
	if len(actions) != 0 {
		t.Errorf("nothing to remove should report nothing, got %v", actions)
	}
}
