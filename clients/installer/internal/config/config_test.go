func TestBindStorageRedefinesTheVolumeNotTheMounts(t *testing.T) {
	/*
	 * backend, rtorrent and qbittorrent all mount downloads:/downloads.
	 * Redefining the VOLUME moves all three together; rewriting three separate
	 * mounts would have to be repeated for every service added later, and the
	 * first one forgotten would silently write somewhere else.
	 */
	p := testPlan()
	p.Storage.Mode = plan.StorageBind
	p.Storage.MediaRoot = "/srv/media"
	p.Finalize()

	got := RenderOverride(p)
	if !strings.Contains(got, "volumes:") || !strings.Contains(got, "downloads:") {
		t.Fatalf("expected a volume redefinition:\n%s", got)
	}
	if !strings.Contains(got, "device: /srv/media") {
		t.Errorf("the host path should be the bind device:\n%s", got)
	}
	// The in-container path must be untouched, or FILE_MANAGER_ROOTS breaks.
	if strings.Contains(got, "/srv/media:/downloads") {
		t.Error("must not rewrite per-service mounts — redefine the volume instead")
	}
}

func TestPUIDAppliesToTheBackendToo(t *testing.T) {
	/*
	 * Ownership is two-sided. PUID/PGID in .env reach the bundled engine, but
	 * the BACKEND writes into the same tree — imports, renames, artwork — as its
	 * own image user. Setting only the engine leaves files the engine cannot
	 * manage, and it surfaces much later as a permission error mid-import.
	 */
	p := testPlan()
	p.Torrent.PUID, p.Torrent.PGID = 997, 997
	p.Finalize()

	got := RenderOverride(p)
	if !strings.Contains(got, `user: "997:997"`) {
		t.Errorf("the backend should run as the media owner:\n%s", got)
	}
}

